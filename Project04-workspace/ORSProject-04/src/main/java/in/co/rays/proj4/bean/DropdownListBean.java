
package in.co.rays.proj4.bean;

/**
 * DropdownListBean interface provides methods to get
 * key and value for dropdown list items.
 * 
 * @author Abhay Malve
 * @version 1.0
 */
public interface DropdownListBean {

	/**
	 * Gets the key of the dropdown item.
	 * 
	 * @return key
	 */
	public String getKey();
	
	/**
	 * Gets the value of the dropdown item.
	 * 
	 * @return value
	 */
	public String getValue();
}
